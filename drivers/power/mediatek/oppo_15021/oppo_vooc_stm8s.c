static int stm8s_driver_probe(struct i2c_client *client, const struct i2c_device_id *id) 
{             
	struct class_device *class_dev = NULL;
    int err=0; 
	struct opchg_fast_charger *chip;
    printk("[stm8s_driver_probe] \n");
	
	init_hw_version();
	if(g_hw_version != HW_VERSION__MCU)
	{
		printk("stm8s_subsys_init err,MCU pic16f\r\n");
		return 0;
	}

	chip = devm_kzalloc(&client->dev, sizeof(*chip), GFP_KERNEL);
    if (!chip) {
        dev_err(&client->dev, "Couldn't allocate memory\n");
        return -ENOMEM;
    }
	chip->client = client;	//stm8s_client = client;
    chip->dev = &client->dev;
	if (!(new_client = kmalloc(sizeof(struct i2c_client), GFP_KERNEL))) {
        err = -ENOMEM;
        goto exit;
    }	
    memset(new_client, 0, sizeof(struct i2c_client));

	new_client = client;
	opchg_fast_charger_chip = chip;	
	chargin_hw_init_done_vooc = KAL_TRUE;
	vooc_fw_update = stm8s_fw_update;
	vooc_fw_ver_count = stm_fw_ver_count;
	vooc_need_to_up_fw = stm_need_to_up_fw;
	vooc_firmware_data = Stm8s_firmware_data;
    stm8s_power(1);
	
	#if GTP_SUPPORT_I2C_DMA	
//	gpDMABuf_va = (u8 *)dma_alloc_coherent(NULL, GTP_DMA_MAX_TRANSACTION_LENGTH, &gpDMABuf_pa, GFP_KERNEL);
	client->dev.coherent_dma_mask = DMA_BIT_MASK(32);
	gpDMABuf_va = (u8 *)dma_alloc_coherent(&client->dev, GTP_DMA_MAX_TRANSACTION_LENGTH, &gpDMABuf_pa, GFP_KERNEL);
	if(!gpDMABuf_va){
        printk("[Error] Allocate DMA I2C Buffer failed!\n");
    }
	else 
		printk(" ppp dma_alloc_coherent success");
    memset(gpDMABuf_va, 0, GTP_DMA_MAX_TRANSACTION_LENGTH);
	#endif
	opchg_set_clk_input_high();
	msleep(20);
	opchg_set_reset_active();
	opchg_fast_charging_works_init_stm8s(chip);
	
    return 0;                                                                                       

exit_kfree:
    kfree(new_client);
    stm8s_power(0);
exit:
    return err;

}


