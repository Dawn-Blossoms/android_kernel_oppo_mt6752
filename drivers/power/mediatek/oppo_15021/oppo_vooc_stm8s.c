static int i2c_dma_read(struct i2c_client *client, u8 addr, s32 len, u8 *rxbuf)
{
    int ret;
    s32 retry = 0;
    u8 buffer[1];
 
    struct i2c_msg msg[2] =
    {
        {
            .addr = (client->addr & I2C_MASK_FLAG),
            .flags = 0,
            .buf = buffer,
            .len = 1,
            .timing = I2C_MASTER_CLOCK
        },
        {
            .addr = (client->addr & I2C_MASK_FLAG),
            .ext_flag = (client->ext_flag | I2C_ENEXT_FLAG | I2C_DMA_FLAG),
            .flags = I2C_M_RD,
            .buf = gpDMABuf_pa,//modified by PengNanppp     
            .len = len,
            .timing = I2C_MASTER_CLOCK
        },
    };
	
	mutex_lock(&dma_wr_access_stm);    
    //buffer[0] = (addr >> 8) & 0xFF;
    buffer[0] = addr & 0xFF;

    if (rxbuf == NULL){
		mutex_unlock(&dma_wr_access_stm); 
        return -1;
    	}
    //printk("vooc dma i2c read: 0x%x, %d bytes(s)", addr, len);
    for (retry = 0; retry < 5; ++retry)
    {
        ret = i2c_transfer(client->adapter, &msg[0], 2);
        if (ret < 0)
        {
            continue;
        }
        memcpy(rxbuf, gpDMABuf_va, len);
		mutex_unlock(&dma_wr_access_stm); 
        return 0;
    }
    //printk("Dma I2C Read Error: 0x%04X, %d byte(s), err-code: %d", addr, len, ret);
	mutex_unlock(&dma_wr_access_stm); 
    return ret;
}


static int i2c_dma_write(struct i2c_client *client, u8 addr, s32 len, u8 *txbuf)
{
    int ret;
    s32 retry = 0;
    u8 *wr_buf = gpDMABuf_va;
    struct i2c_msg msg =
    {
        .addr = (client->addr & I2C_MASK_FLAG),
        .ext_flag = (client->ext_flag | I2C_ENEXT_FLAG | I2C_DMA_FLAG),
        .flags = 0,
        .buf = gpDMABuf_pa,//modified by PengNanppp
        .len = 1 + len,
        .timing = I2C_MASTER_CLOCK
    };
	mutex_lock(&dma_wr_access_stm);  
    wr_buf[0] = (u8)(addr & 0xFF);
    if (txbuf == NULL){
			mutex_unlock(&dma_wr_access_stm); 
			return -1;
    	}
    memcpy(wr_buf+1, txbuf, len);
    for (retry = 0; retry < 5; ++retry)
    {
        ret = i2c_transfer(client->adapter, &msg, 1);
        if (ret < 0)
        {
            continue;
        }
		mutex_unlock(&dma_wr_access_stm); 
        return 0;
    }
    //printk("Dma I2C Write Error: 0x%04X, %d byte(s), err-code: %d", addr, len, ret);
	mutex_unlock(&dma_wr_access_stm); 
    return ret;
}



static int i2c_read_bytes_dma(struct i2c_client *client, u16 addr, u8 *rxbuf, s32 len)
{
    s32 left = len;
    s32 read_len = 0;
    u8 *rd_buf = rxbuf;
    s32 ret = 0;
	
    //mutex_lock(&dma_wr_access_stm);    
    //printk("Read bytes dma: 0x%04X, %d byte(s)", addr, len);
    while (left > 0)
    {
        if (left > GTP_DMA_MAX_TRANSACTION_LENGTH)
        {
            read_len = GTP_DMA_MAX_TRANSACTION_LENGTH;
        }
        else
        {
            read_len = left;
        }
        ret = i2c_dma_read(client, addr, read_len, rd_buf);
        if (ret < 0)
        {
            printk("dma read failed");
			//mutex_unlock(&dma_wr_access_stm);
            return -1;
        }
        
        left -= read_len;
        addr += read_len;
        rd_buf += read_len;
    }
    //mutex_unlock(&dma_wr_access_stm);
    return 0;
}

